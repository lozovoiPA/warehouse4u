CREATE TABLE products (
    id       integer      GENERATED BY DEFAULT AS IDENTITY
                          PRIMARY KEY,
    name     varchar(100) NOT NULL,
    category varchar(50)  DEFAULT NULL,
    unit     varchar(50)  DEFAULT NULL,
    sku      varchar(50)  NOT NULL DEFAULT '',
    CONSTRAINT sku UNIQUE (sku)
);

CREATE SEQUENCE sku_seq START WITH 1;

CREATE OR REPLACE FUNCTION transliterate_cyrillic(input_string text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    result text := input_string;
    mapping record;
BEGIN
    FOR mapping IN
        SELECT * FROM (VALUES
            ('А','A'), ('Б','B'), ('В','V'), ('Г','G'), ('Д','D'),
            ('Е','E'), ('Ё','Yo'), ('Ж','Zh'), ('З','Z'), ('И','I'),
            ('Й','Y'), ('К','K'), ('Л','L'), ('М','M'), ('Н','N'),
            ('О','O'), ('П','P'), ('Р','R'), ('С','S'), ('Т','T'),
            ('У','U'), ('Ф','F'), ('Х','Kh'), ('Ц','Ts'), ('Ч','Ch'),
            ('Ш','Sh'), ('Щ','Shch'), ('Ъ',''), ('Ы','Y'), ('Ь',''),
            ('Э','E'), ('Ю','Yu'), ('Я','Ya'),
            ('а','a'), ('б','b'), ('в','v'), ('г','g'), ('д','d'),
            ('е','e'), ('ё','yo'), ('ж','zh'), ('з','z'), ('и','i'),
            ('й','y'), ('к','k'), ('л','l'), ('м','m'), ('н','n'),
            ('о','o'), ('п','p'), ('р','r'), ('с','s'), ('т','t'),
            ('у','u'), ('ф','f'), ('х','kh'), ('ц','ts'), ('ч','ch'),
            ('ш','sh'), ('щ','shch'), ('ъ',''), ('ы','y'), ('ь',''),
            ('э','e'), ('ю','yu'), ('я','ya')
        ) AS t(from_char, to_char)
    LOOP
        result := replace(result, mapping.from_char, mapping.to_char);
    END LOOP;
    RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION before_insert_products_fn()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    next_sku_num text;
    translit     text;
    word         text;
    stripped     text := '';
    words        text[];
BEGIN
    next_sku_num := nextval('sku_seq')::text;

    translit := upper(transliterate_cyrillic(NEW.name));

    words := string_to_array(translit, ' ');

    FOREACH word IN ARRAY words
    LOOP
        IF word = '' THEN
            CONTINUE;
        END IF;

        word := substring(word from 1 for 1)
             || regexp_replace(substring(word from 2), '[AEIOU]', '', 'g');

        stripped := stripped || ' ' || word;
    END LOOP;
    stripped := regexp_replace(stripped, ' ([^ -]{1,4})[^ -]*', '-\1', 'g');
    stripped := substring(stripped from 2);

    NEW.sku := stripped || '-' || next_sku_num;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER before_insert_products
BEFORE INSERT ON products
FOR EACH ROW
EXECUTE FUNCTION before_insert_products_fn();

