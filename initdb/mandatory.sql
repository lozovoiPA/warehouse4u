CREATE OR REPLACE FUNCTION check_stock_before_movement()
RETURNS TRIGGER AS $$
DECLARE
    available INTEGER;
BEGIN
    IF NEW.out_warehouse_id = NEW.in_warehouse_id THEN
        RAISE EXCEPTION 'Source and destination warehouses must differ';
    END IF;

    -- Lock the source stock row to prevent concurrent over-selling.
    -- FOR UPDATE requires the row to exist; if it does not, `available` stays NULL.
    SELECT quantity
      INTO available
      FROM stock_items
     WHERE product_id   = NEW.product_id
       AND warehouse_id = NEW.out_warehouse_id
     FOR UPDATE;

    IF available IS NULL OR available < NEW.quantity THEN
        RAISE EXCEPTION
            'Insufficient stock for product % in warehouse %: available %, requested %',
            NEW.product_id, NEW.out_warehouse_id,
            COALESCE(available, 0), NEW.quantity;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_stock_before_movement
BEFORE INSERT ON movements
FOR EACH ROW
EXECUTE FUNCTION check_stock_before_movement();


CREATE OR REPLACE FUNCTION apply_movement_stock()
RETURNS TRIGGER AS $$
DECLARE
    remaining INTEGER;
BEGIN
    -- 1) Decrement (or delete) the source stock item
    SELECT quantity INTO remaining FROM stock_items
     WHERE product_id   = NEW.product_id
       AND warehouse_id = NEW.out_warehouse_id;

    IF remaining = NEW.quantity THEN
        DELETE FROM stock_items
         WHERE product_id   = NEW.product_id
           AND warehouse_id = NEW.out_warehouse_id;
    END IF;

    IF remaining > NEW.quantity THEN
	UPDATE stock_items
          SET quantity = quantity - NEW.quantity
          WHERE product_id   = NEW.product_id
            AND warehouse_id = NEW.out_warehouse_id;
    END IF;

    -- 2) Increment the destination stock item, inserting if it doesn't exist
    INSERT INTO stock_items (product_id, warehouse_id, quantity)
    VALUES (NEW.product_id, NEW.in_warehouse_id, NEW.quantity)
    ON CONFLICT (product_id, warehouse_id)
    DO UPDATE SET quantity = stock_items.quantity + EXCLUDED.quantity;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_apply_movement_stock
AFTER INSERT ON movements
FOR EACH ROW
EXECUTE FUNCTION apply_movement_stock();

